#!/usr/bin/env bash
# Connect to a CompShare container over SSH, refreshing the endpoint on every run.
#
# Why this exists: the system /etc/ssh/ssh_config is unusable in this environment —
# /etc/ssh/ssh_config.d and its 20-systemd-ssh-proxy.conf are owned by nobody:nogroup and
# there is no root access, so plain `ssh` aborts with
#   Bad owner or permissions on /etc/ssh/ssh_config.d/20-systemd-ssh-proxy.conf
# We bypass it by pointing ssh at a config we generate ourselves (-F). The same breakage is
# what stops `compshare instance ssh` / `compshare instance job` from working.
#
# CompShare hands out a new host/port on every start, so the endpoint is re-read from
# `compshare instance ssh --print` each time and written to .dsh-ssh/config.auto.
#
#   ./connect-container.sh                      # interactive shell
#   ./connect-container.sh nvidia-smi           # one remote command
#   ./connect-container.sh -- sh -lc 'ls -l'    # remote shell syntax
#   scp -F .dsh-ssh/config.auto ./local.file inst-container:/workspace/   # also works
#
# Environment overrides: COMPSHARE_INSTANCE, CONTAINER_SSH_KEY, CONTAINER_SSH_VERBOSE=1.

set -euo pipefail

INSTANCE="${COMPSHARE_INSTANCE:-cpod-1xlyk0covudm}"
ROOT="$(cd "$(dirname "$0")" && pwd)"
STATE="$ROOT/.dsh-ssh"
CFG="$STATE/config.auto"
LEGACY="$STATE/config"
KEY="${CONTAINER_SSH_KEY:-$HOME/.ssh/remote-dsh.pem}"

log() { [[ "${CONTAINER_SSH_VERBOSE:-0}" == "1" ]] && echo "$*" >&2 || true; }

ssh_command() {
  compshare --json instance ssh "$INSTANCE" --print --no-wait 2>/dev/null |
    python3 -c 'import json,sys; print(json.load(sys.stdin)["data"]["command"])' 2>/dev/null || true
}

endpoint() {  # "host port" parsed out of the ssh command line printed by the CLI
  python3 - "$1" <<'PY'
import shlex, sys
argv = shlex.split(sys.argv[1])
port, host = "22", ""
for i, a in enumerate(argv):
    if a in ("-p", "-P") and i + 1 < len(argv):
        port = argv[i + 1]
    elif a.startswith("-p") and len(a) > 2:
        port = a[2:]
    elif "@" in a and not a.startswith("-"):
        host = a.rsplit("@", 1)[1]
print(host, port)
PY
}

CMD="$(ssh_command)"
if [[ -n "$CMD" ]]; then
  read -r HOST PORT <<<"$(endpoint "$CMD")"
fi

if [[ -z "${HOST:-}" || -z "${PORT:-}" ]]; then
  echo "connect-container: no SSH endpoint for $INSTANCE (is the instance Running?)" >&2
  if [[ -f "$LEGACY" ]]; then
    echo "connect-container: falling back to the hand-written $LEGACY" >&2
    exec ssh -F "$LEGACY" inst-container "$@"
  fi
  exit 1
fi

mkdir -p "$STATE"
umask 077
cat >"$CFG" <<EOF
# Generated by connect-container.sh — rewritten on every run, do not edit.
Host inst-container
  HostName $HOST
  Port $PORT
  User root
  IdentityFile $KEY
  IdentitiesOnly yes
  StrictHostKeyChecking accept-new
  UserKnownHostsFile $STATE/known_hosts
  ServerAliveInterval 30
  ServerAliveCountMax 3
EOF

log "connect-container: $INSTANCE -> $HOST:$PORT (key $KEY)"
exec ssh -F "$CFG" inst-container "$@"
